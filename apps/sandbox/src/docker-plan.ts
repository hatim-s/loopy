import type { SandboxConfig } from "./config.js";
import type { StartedReceipt } from "./receipts.js";

export function inputContainerArgs(config: SandboxConfig, receipt: StartedReceipt, owner: string) {
  const helper = `${receipt.container}-input`;

  return [
    "create",
    "--name",
    helper,
    "--label",
    `loopy.sandbox.owner=${owner}`,
    "--label",
    `loopy.sandbox.request=${receipt.requestHash}`,
    "--network",
    "none",
    "--user",
    "1000:1000",
    "--cap-drop",
    "ALL",
    "--security-opt",
    "no-new-privileges:true",
    "--read-only",
    "--mount",
    `type=volume,source=${receipt.inputVolume},target=/input`,
    config.image,
  ];
}

export function attemptContainerArgs(
  config: SandboxConfig,
  receipt: StartedReceipt,
  owner: string,
) {
  return [
    "create",
    "--name",
    receipt.container,
    "--label",
    `loopy.sandbox.owner=${owner}`,
    "--label",
    `loopy.sandbox.request=${receipt.requestHash}`,
    "--network",
    "none",
    "--user",
    "1000:1000",
    "--cap-drop",
    "ALL",
    "--security-opt",
    "no-new-privileges:true",
    "--read-only",
    "--tmpfs",
    "/tmp:rw,noexec,nosuid,size=64m,mode=1777",
    "--memory",
    config.memory,
    "--memory-swap",
    config.memory,
    "--cpus",
    String(config.cpus),
    "--pids-limit",
    String(config.pids),
    "--ulimit",
    "nofile=256:256",
    "--init",
    "--log-driver",
    "local",
    "--log-opt",
    "max-size=4m",
    "--log-opt",
    "max-file=1",
    "--log-opt",
    "compress=false",
    "--mount",
    `type=volume,source=${receipt.volume},target=/workspace`,
    "--mount",
    `type=volume,source=${receipt.inputVolume},target=/input,readonly`,
    "--workdir",
    "/workspace",
    "--env",
    "HOME=/workspace",
    "--env",
    "TMPDIR=/tmp",
    "--entrypoint",
    "bun",
    config.image,
    "/opt/loopy/worker.js",
  ];
}
