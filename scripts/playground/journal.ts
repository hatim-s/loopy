import { appendFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { z } from "zod";
import { atomic, state } from "./config";

export const inputSchema = z.strictObject({
  batch: z.string(),
  ordinal: z.number().int(),
  fail: z.boolean(),
  items: z.array(z.number()),
});

export const admissionSchema = z.strictObject({
  slug: z.string(),
  group: z.enum(["a", "b", "c"]),
  phase: z.enum(["preflight", "primary"]),
  input: inputSchema,
  expected: z.enum(["succeeded", "failed"]),
  intentAt: z.string(),
  admittedAt: z.string().nullable(),
  runId: z.string().nullable(),
});

export type Admission = z.infer<typeof admissionSchema>;

export type Group = Admission["group"];

export async function record(path: string, value: Admission) {
  await atomic(path, admissionSchema.parse(value));
}

// BOUNDARY: Events accept diagnostic JSON generated by the driver and never credentials.
export async function event(group: Group, value: unknown) {
  await mkdir(resolve(state, "journal"), { recursive: true });
  await appendFile(
    resolve(state, "journal", `${group}.jsonl`),
    `${JSON.stringify({ at: new Date().toISOString(), ...z.record(z.string(), z.unknown()).parse(value) })}\n`,
    { mode: 0o600 },
  );
}

export const waitSchema = z.strictObject({
  hook: z.string(),
  observedAt: z.string(),
  dueAt: z.number(),
  resolvedAt: z.string().nullable(),
});

export const artifactRecordSchema = z.strictObject({
  expectedPath: z.string(),
  destination: z.string(),
  sha256: z.string(),
  bytes: z.number(),
});

export const resultSchema = z.strictObject({
  runId: z.string(),
  slug: z.string(),
  expected: z.enum(["succeeded", "failed"]),
  actual: z.enum(["succeeded", "failed"]),
  classification: z.enum(["success", "controlled-failure"]),
  wait: waitSchema.nullable(),
  artifact: artifactRecordSchema.nullable(),
});

export const progressSchema = z.strictObject({
  wait: waitSchema.nullable(),
  approvalIntentAt: z.string().nullable(),
  result: resultSchema.nullable(),
});

export type Progress = z.infer<typeof progressSchema>;
